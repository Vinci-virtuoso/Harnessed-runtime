class StubOpener:
    """Stands in for ``urlopen`` one layer below ``JevDecider.decide``, like
    ``providers/pricing.py``'s test double. Never opens a socket."""

    def __init__(self, *, body: bytes | None = None, raises: BaseException | None = None) -> None:
        self._body = body
        self._raises = raises
        self.calls: list[tuple[object, float]] = []

    def __call__(self, request: object, timeout: float) -> io.BytesIO:
        self.calls.append((request, timeout))
        if self._raises is not None:
            raise self._raises
        assert self._body is not None
        return io.BytesIO(self._body)


