def test_each_question_type_parses_into_its_typed_answer() -> None:
    decisions = jev.parse(recorded("one_of_each.json"), QUESTIONS)

    assert isinstance(decisions.answers["needs_memory"], jev.Noul)
    assert decisions.answers["needs_memory"].probability == Decimal("0.85")

    route = decisions.answers["route"]
    assert isinstance(route, jev.Choice)
    assert route.value == CLAUDE
    assert route.confidence == Decimal("0.96")
    assert route.probabilities == {
        "groq_chat": Decimal("0.02"),
        CLAUDE: Decimal("0.96"),
        "needs_human": Decimal("0.02"),
    }

    risk = decisions.answers["risk"]
    assert isinstance(risk, jev.Score)
    assert risk.value == "low"
    assert risk.confidence == Decimal("0.78")
    assert risk.legend == {"0": "low", "1": "medium", "2": "high"}
    assert risk.probabilities["0"] == Decimal("0.78")

    lines = [
        f"{name}: {type(answer).__name__} {answer}" for name, answer in decisions.answers.items()
    ]
    capture("answers.txt", "\n".join(lines) + "\n")


