def test_no_fixture_keeps_the_assumed_answer_shape() -> None:
    """MUST rule 8: every Jev fixture is the recorded shape - no `value` or `probability` answer
    key and no string cost."""
    offenders = []
    for path in sorted(FIXTURES.rglob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        for name, answer in payload.get("answers", {}).items():
            if not isinstance(answer, dict) or {"value", "probability"} & set(answer):
                offenders.append(f"{path.relative_to(FIXTURES)}: {name}")
            elif answer.get("type") not in {"choice", "noul", "score"}:
                offenders.append(f"{path.relative_to(FIXTURES)}: {name} has no type")
        if isinstance(payload.get("usage", {}).get("cost"), str):
            offenders.append(f"{path.relative_to(FIXTURES)}: string cost")
    assert offenders == []


def test_the_decider_takes_a_tuple_of_roots_and_refuses_a_shadowing_scope(
    fake_settings: config.Settings, tmp_path: Path
) -> None:
    import shutil

    from harnessed.errors import FixtureCorpusError

    shipped_root = fake_decider.DEFAULT_CORPUS_ROOT
    scope = sorted(path.parent.name for path in shipped_root.glob("*/_index.yaml"))[0]
    home_root = tmp_path / "home"
    shutil.copytree(shipped_root / scope, home_root / scope)

